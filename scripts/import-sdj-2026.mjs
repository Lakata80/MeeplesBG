async function main() {
  // Провери дали вече съществува статия с този slug
  const existing = await client.fetch(
    `*[_type == "post" && slug.current == $slug][0]._id`,
    { slug: doc.slug.current }
  )

  if (existing) {
    console.log(`⚠️  Статия с slug "${doc.slug.current}" вече съществува (_id: ${existing}).`)
    console.log('   Ако искаш да я презапишеш, добави --force като аргумент.')
    if (!process.argv.includes('--force')) process.exit(0)
    const updated = await client.patch(existing).set(doc).commit()
    console.log(`✅  Обновена: ${updated._id}`)
  } else {
    const created = await client.create(doc)
    console.log(`✅  Статията е създадена!`)
    console.log(`   _id: ${created._id}`)
    console.log(`   Отвори Studio → Posts → намери "Spiel des Jahres 2026" → добави главна снимка → Publish`)
  }
}

